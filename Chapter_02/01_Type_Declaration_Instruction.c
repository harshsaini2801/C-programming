#include <stdio.h>

int main() { 
    int i = 10; // Declare 'i' and initialize with 10
    int j = i;
    int a = 2, b = 3, c = 4, d = 5;  // Declare and initialize multiple variables
    //%d is called format specifier
    //%d is for int %f for float and %c for char
    printf("The value of i is is %d and value of j is %d\n", i , j );
    printf("The value of a is is %d and value of b is %d\n", a , b );
    printf("The value of c is is %d and value of d is %d\n", c , d );
} 